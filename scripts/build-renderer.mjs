#!/usr/bin/env node
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "renderer");
mkdirSync(outDir, { recursive: true });

await build({
  root,
  configFile: false,
  publicDir: false,
  logLevel: "silent",
  build: {
    emptyOutDir: false,
    copyPublicDir: false,
    outDir,
    minify: true,
    lib: {
      entry: join(root, "src/lib/studio/renderer/runtime.ts"),
      name: "AetherRuntimeModule",
      formats: ["iife"],
      fileName: () => "aether-runtime.js",
    },
    rollupOptions: {
      output: {
        inlineDynamicImports: true,
      },
    },
  },
});

const jsCode = readFileSync(join(outDir, "aether-runtime.js"), "utf8");
const tsWrapper = `// Auto-generated by scripts/build-renderer.mjs — do not edit by hand.\nexport const AETHER_RUNTIME_JS = ${JSON.stringify(jsCode)};\n`;
writeFileSync(join(root, "src/lib/studio/renderer/runtime-bundle.ts"), tsWrapper, "utf8");
console.log(`[build-renderer] wrote public/renderer/aether-runtime.js (${jsCode.length} bytes)`);
